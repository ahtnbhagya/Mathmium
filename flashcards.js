// FORMAT FRACTIONS
// Converts \\frac{a}{b} into stacked fractions
// =========================================================

function renderMathText(element, text) {

    element.textContent = "";

    const fractionPattern = /\\frac\{([^{}]+)\}\{([^{}]+)\}/g;

    let lastIndex = 0;
    let match;

    while ((match = fractionPattern.exec(text)) !== null) {

        // Add normal text before the fraction.
        element.appendChild(
            document.createTextNode(text.slice(lastIndex, match.index))
        );

        // Create the fraction container.
        const fraction = document.createElement("span");
        fraction.className = "math-fraction";

        const numerator = document.createElement("span");
        numerator.className = "numerator";
        numerator.textContent = match[1];

        const denominator = document.createElement("span");
        denominator.className = "denominator";
        denominator.textContent = match[2];

        fraction.appendChild(numerator);
        fraction.appendChild(denominator);

        element.appendChild(fraction);

        lastIndex = fractionPattern.lastIndex;

    }

    // Add any remaining text.
    element.appendChild(
        document.createTextNode(text.slice(lastIndex))
    );

    // Display the pi symbol if written as \pi.
    element.childNodes.forEach(function (node) {

        if (node.nodeType === Node.TEXT_NODE) {
            node.textContent = node.textContent.replace(/\\pi/g, "π");
        }

    });

}


