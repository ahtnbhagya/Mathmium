// =========================================================
// FLASHCARD FUNCTIONALITY
// =========================================================

document.addEventListener("DOMContentLoaded", function () {

    const subjectGrid = document.getElementById("subject-grid");
    const emptyMessage = document.getElementById("empty-message");

    const studyWindow = document.getElementById("study-window");
    const studySubject = document.getElementById("study-subject");

    const cardCounter = document.getElementById("card-counter");
    const progressPercentage = document.getElementById("progress-percentage");
    const progressFill = document.getElementById("progress-fill");

    const cardStage = document.getElementById("card-stage");
    const questionText = document.getElementById("question-text");
    const answerText = document.getElementById("answer-text");

    const backButton = document.getElementById("back-button");
    const previousButton = document.getElementById("previous-button");
    const nextButton = document.getElementById("next-button");
    const shuffleButton = document.getElementById("shuffle-button");

    let currentSubject = null;
    let currentCards = [];
    let currentIndex = 0;


    // -----------------------------------------------------
    // GENERATE SUBJECT BUTTONS
    // -----------------------------------------------------

    function generateSubjects() {

        subjectGrid.innerHTML = "";

        if (!flashcardSubjects.length) {
            emptyMessage.style.display = "block";
            return;
        }

        emptyMessage.style.display = "none";

        const colors = [
            ["#159E94", "#CFFFF7", "#087D76"],
            ["#3978D4", "#DCEBFF", "#245BA9"],
            ["#D95F00", "#FFD0A0", "#A94700"]
        ];

        flashcardSubjects.forEach(function (subject, index) {

            const color = colors[index % colors.length];

            const button = document.createElement("button");

            button.type = "button";
            button.className = "subject-card";

            button.style.setProperty("--subject-color", color[0]);
            button.style.setProperty("--subject-light", color[1]);
            button.style.setProperty("--subject-dark", color[2]);

            const name = document.createElement("span");
            name.className = "subject-name";
            name.textContent = subject.name;

            const count = document.createElement("span");
            count.className = "subject-count";
            count.textContent = subject.cards.length + " Flashcards";

            const arrow = document.createElement("span");
            arrow.className = "subject-arrow";
            arrow.textContent = "→";
            arrow.setAttribute("aria-hidden", "true");

            button.appendChild(name);
            button.appendChild(count);
            button.appendChild(arrow);

            button.addEventListener("click", function () {
                openSubject(subject);
            });

            subjectGrid.appendChild(button);

        });

    }


    // -----------------------------------------------------
    // OPEN SELECTED SUBJECT
    // -----------------------------------------------------

    function openSubject(subject) {

        currentSubject = subject;

        currentCards = subject.cards.map(function (card) {
            return { ...card };
        });

        currentIndex = 0;

        studySubject.textContent = subject.name;

        document.getElementById("subject-section").style.display = "none";

        studyWindow.classList.add("active");

        displayCard();

        studyWindow.scrollIntoView({
            behavior: "smooth",
            block: "start"
        });

    }


    // -----------------------------------------------------
    // DISPLAY FLASHCARD
    // -----------------------------------------------------

    function displayCard() {

        if (!currentCards.length) return;

        const card = currentCards[currentIndex];

        questionText.textContent = card.question;
        answerText.textContent = card.answer;

        cardStage.classList.remove("flipped");

        cardStage.setAttribute("aria-pressed", "false");

        cardStage.setAttribute(
            "aria-label",
            "Question: " + card.question + ". Activate to reveal the answer."
        );

        updateProgress();

        previousButton.disabled = currentIndex === 0;

        nextButton.disabled = currentIndex === currentCards.length - 1;

    }


    // -----------------------------------------------------
    // UPDATE PROGRESS
    // -----------------------------------------------------

    function updateProgress() {

        const total = currentCards.length;

        const completed = currentIndex + 1;

        const percentage = Math.round((completed / total) * 100);

        cardCounter.textContent =
            "Card " + completed + " of " + total;

        progressPercentage.textContent =
            percentage + "% completed";

        progressFill.style.width = percentage + "%";

    }


    // -----------------------------------------------------
    // FLIP FLASHCARD
    // -----------------------------------------------------

    function flipCard() {

        cardStage.classList.toggle("flipped");

        const isFlipped = cardStage.classList.contains("flipped");

        cardStage.setAttribute(
            "aria-pressed",
            String(isFlipped)
        );

        cardStage.setAttribute(
            "aria-label",
            isFlipped
                ? "Answer: " + currentCards[currentIndex].answer + ". Activate to see the question."
                : "Question: " + currentCards[currentIndex].question + ". Activate to reveal the answer."
        );

    }

    cardStage.addEventListener("click", flipCard);

    cardStage.addEventListener("keydown", function (event) {

        if (event.key === "Enter" || event.key === " ") {

            event.preventDefault();

            flipCard();

        }

    });


    // -----------------------------------------------------
    // NEXT CARD
    // -----------------------------------------------------

    nextButton.addEventListener("click", function () {

        if (currentIndex < currentCards.length - 1) {

            currentIndex++;

            displayCard();

        }

    });


    // -----------------------------------------------------
    // PREVIOUS CARD
    // -----------------------------------------------------

    previousButton.addEventListener("click", function () {

        if (currentIndex > 0) {

            currentIndex--;

            displayCard();

        }

    });


    // -----------------------------------------------------
    // SHUFFLE CARDS
    // -----------------------------------------------------

    shuffleButton.addEventListener("click", function () {

        for (let i = currentCards.length - 1; i > 0; i--) {

            const j = Math.floor(Math.random() * (i + 1));

            [currentCards[i], currentCards[j]] =
                [currentCards[j], currentCards[i]];

        }

        currentIndex = 0;

        displayCard();

    });


    // -----------------------------------------------------
    // BACK TO SUBJECTS
    // -----------------------------------------------------

    backButton.addEventListener("click", function () {

        studyWindow.classList.remove("active");

        document.getElementById("subject-section").style.display = "block";

        currentSubject = null;
        currentCards = [];
        currentIndex = 0;

        document.getElementById("subject-section").scrollIntoView({
            behavior: "smooth",
            block: "start"
        });

    });


    // -----------------------------------------------------
    // INITIALISE FLASHCARD ZONE
    // -----------------------------------------------------

    generateSubjects();

});
